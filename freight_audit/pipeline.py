OWNED = ("data", "ground_truth", "reports", "docs", "manifest.json")


def run(cfg: C.ScaleConfig, seed: int, out_dir: str | Path, formats=("csv", "json", "sql"), quiet=False) -> dict:
    t0 = time.time()
    log = (lambda *a: None) if quiet else (lambda *a: print(*a, flush=True))
    out = Path(out_dir)
    for name in OWNED:   # only remove what this tool writes; files first (synced folders may lock dirs)
        p = out / name
        if p.is_dir():
            for f in sorted(p.rglob("*"), reverse=True):
                if f.is_file():
                    f.unlink()
            shutil.rmtree(p, ignore_errors=True)
        elif p.exists():
            p.unlink()
    out.mkdir(parents=True, exist_ok=True)

    log(f"[1/6] generating scale={cfg.name} seed={seed}")
    gen = generate(cfg, seed)
    tables = dict(gen.tables)
    log("[2/6] auditing invoices")
    audit = run_audit(tables, seed)
    log("[3/6] dispute workflow, carrier credits, reconciliation")
    st = run_settlement(tables, audit, seed)
    tables.update(st.tables)
    ground_truth = gen.ground_truth + st.ground_truth
    for n, g in enumerate(ground_truth, 1):
        g["gt_id"] = ground_truth_id(n)

    log("[4/6] exporting")
    for t in TABLES:
        rows = tables[t.name]
        if "csv" in formats:
            write_csv(out / "data" / "csv" / f"{t.name}.csv", t.columns, rows)
        if "json" in formats:
            write_json(out / "data" / "json" / f"{t.name}.json", t.columns, rows)
    db = write_sql(out / "data" / "sql", tables, seed_sql="sql" in formats)
    gtd = out / "ground_truth"
    write_csv(gtd / "ground_truth.csv", GROUND_TRUTH_COLUMNS, ground_truth)
    write_json(gtd / "ground_truth.json", GROUND_TRUTH_COLUMNS, ground_truth)
    write_csv(gtd / "expected_line_charges.csv", EXPECTED_LINE_COLUMNS, gen.expected_line_charges)
    write_csv(gtd / "expected_invoice_outcomes.csv", EXPECTED_INVOICE_COLUMNS, gen.expected_invoice_outcomes)
    write_text(out / "docs" / "DATA_DICTIONARY.md", data_dictionary_md())

    log("[5/6] validating")
    validation = validate(tables, ground_truth, gen.expected_line_charges, gen.expected_invoice_outcomes, str(db))
    write_json_doc(out / "reports" / "validation_summary.json", validation)
    write_text(out / "reports" / "validation_summary.md", validation_md(validation, cfg, seed))

    log("[6/6] evaluating against ground truth")
    metrics = evaluate(tables, ground_truth, gen.expected_line_charges, gen.expected_invoice_outcomes)
    metrics["generator_notes"] = gen.notes
    write_json_doc(out / "reports" / "evaluation_metrics.json", metrics)
    write_text(out / "reports" / "evaluation_report.md", evaluation_md(metrics, cfg, seed))
    sc = carrier_scorecard(tables)
    write_csv(out / "reports" / "carrier_scorecard.csv", list(sc[0].keys()), sc)

    files = []
    for p in sorted(out.rglob("*")):
        if p.is_file() and p.name != "manifest.json":
            rel = p.relative_to(out).as_posix()
            rows = None
            if p.suffix == ".csv":
                with open(p, encoding="utf-8") as fh:
                    rows = sum(1 for _ in fh) - 1
            files.append({"path": rel, "bytes": p.stat().st_size, "rows": rows, "sha256": sha256(p)})
    manifest = {
        "generator": "freight_audit", "generator_version": C.GENERATOR_VERSION, "seed": seed,
        "scale": cfg.__dict__, "as_of": C.AS_OF_END.isoformat(),
        "command": f"python -m freight_audit run --scale {cfg.name} --seed {seed}",
        "data_provenance": "100% synthetic, generated by this repository. No external datasets. City coordinates "
                           "are approximate public facts used only to derive distances.",
        "row_counts": {t.name: len(tables[t.name]) for t in TABLES},
        "ground_truth_rows": len(ground_truth), "validation": validation["overall"],
        "generated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "runtime_seconds": round(time.time() - t0, 1),
        "python": sys.version.split()[0], "platform": platform.platform(),
        "files": files,
    }
    write_json_doc(out / "manifest.json", manifest)
    det = metrics["exception_detection"]["micro"]
    log(f"done in {manifest['runtime_seconds']}s -> {out}  validation={validation['overall']} "
        f"({validation['checks_total'] - validation['checks_failed']}/{validation['checks_total']} checks)  "
        f"detection P={det['precision']} R={det['recall']}  "
        f"expected-charge match={metrics['expected_charge_reproduction']['line_match_rate']}")
    return {"manifest": manifest, "validation": validation, "metrics": metrics}


def validation_md(v: dict, cfg, seed) -> str:
    lines = [f"# Validation summary — scale `{cfg.name}`, seed `{seed}`", "",
             f"**Overall: {v['overall']}** — {v['checks_total'] - v['checks_failed']}/{v['checks_total']} checks passed.",
             "", "| Category | Pass | Fail |", "|---|---|---|"]
    for cat, c in v["by_category"].items():
        lines.append(f"| {cat} | {c['PASS']} | {c['FAIL']} |")
    lines += ["", "Checks with *expected* violations pass only when the violations are exactly the labelled "
              "ground-truth cases (e.g. invoices that deliberately reference an unknown shipment).", "",
              "| Check | Category | Status | Violations (expected) | Description |", "|---|---|---|---|---|"]
    for c in v["checks"]:
        if c["category"] in ("REQUIRED", "TYPE", "ENUM", "ID_FORMAT", "UNIQUE", "PRIMARY_KEY") and \
                c["status"] == "PASS":
            continue
        lines.append(f"| `{c['check_id']}` | {c['category']} | {c['status']} | {c['violations']} "
                     f"({c['expected_violations']}) | {c['description']} |")
    lines += ["", "_Per-table PRIMARY_KEY / REQUIRED / TYPE / ENUM / ID_FORMAT / UNIQUE checks that passed are "
              "omitted above for brevity; all are listed in `validation_summary.json`._", ""]
    return "\n".join(lines)


def evaluation_md(m: dict, cfg, seed) -> str:
    e, d, x = m["expected_charge_reproduction"], m["exception_detection"], m["explanation_completeness"]
    k, cr, p = m["business_kpis"], m["credit_reconciliation"], m["data_profile"]
    L = [f"# Evaluation report — scale `{cfg.name}`, seed `{seed}`", "",
         "Audit outputs compared with `ground_truth/` (which the audit engine never reads).", "",
         "## Acceptance criteria", "",
         "| Criterion | Measure | Result |", "|---|---|---|",
         f"| Expected charges are reproducible | lines whose re-rated expected amount equals ground truth | "
         f"{e['lines_exact_match']}/{e['lines']} ({e['line_match_rate']:.2%}) |",
         f"| Exceptions explain line-level differences | lines with variance not covered by an exception or "
         f"tolerance | {x['lines_with_unexplained_variance']} |",
         f"| Duplicate bills are detected | DUPLICATE_INVOICE recall / precision | "
         f"{d['per_issue_type'].get('DUPLICATE_INVOICE', {}).get('recall')} / "
         f"{d['per_issue_type'].get('DUPLICATE_INVOICE', {}).get('precision')} |",
         f"| Credits reconcile to approved disputes | credits without approved dispute; over-credits flagged "
         f"(recall) | {cr['credits_without_approved_dispute']}; {cr['over_credit_detection']['recall']} |",
         "", "## Exception detection by issue type (invoice level)", "",
         "| Issue type | TP | FP | FN | Precision | Recall | F1 |", "|---|---|---|---|---|---|---|"]
    for ty, r in d["per_issue_type"].items():
        L.append(f"| {ty} | {r['tp']} | {r['fp']} | {r['fn']} | {r['precision']} | {r['recall']} | {r['f1']} |")
    mi = d["micro"]
    L += [f"| **micro** | {mi['tp']} | {mi['fp']} | {mi['fn']} | {mi['precision']} | {mi['recall']} | {mi['f1']} |",
          "", f"False-positive rate on non-anomalous invoices: {d['false_positive_rate_non_anomalous']}. "
          f"Exact label match rate: {d['exact_label_match_rate']}.", "",
          "| Scenario class | Invoices | With exception |", "|---|---|---|"]
    for c, r in d["by_scenario_class"].items():
        L.append(f"| {c} | {r['invoices']} | {r['with_exception']} |")
    L += ["", f"Decision accuracy: {m['decision_accuracy']['accuracy']} — "
          + ", ".join(f"{k2}: {v}" for k2, v in m["decision_accuracy"]["confusion_expected_vs_predicted"].items()),
          "", "## Business KPIs", "", "| KPI | Value |", "|---|---|"]
    for key in ("invoices_audited", "billed_amount", "expected_amount", "invoice_exception_rate",
                "overbilling_identified_amount", "rejected_invoice_amount_prevented", "disputed_amount",
                "lost_to_late_dispute_amount", "late_dispute_rejections", "net_savings_amount", "savings_rate_of_billed"):
        L.append(f"| {key} | {k[key]} |")
    L += [f"| decisions | {k['decisions']} |", f"| exceptions_by_status | {k['exceptions_by_status']} |", "",
          "## Credit reconciliation", "", "| Measure | Value |", "|---|---|"]
    for key, val in cr.items():
        L.append(f"| {key} | {val} |")
    L += ["", "## Data profile (realism)", "", "| Measure | Value |", "|---|---|"]
    for key, val in p.items():
        L.append(f"| {key} | {val} |")
    L.append("")
    return "\n".join(L)


def reproducibility(cfg: C.ScaleConfig, seed: int, work: Path, reference: Path | None) -> dict:
    """Run the pipeline twice with the same seed and compare every output file checksum."""
    runs = []
    for i in (1, 2):
        d = work / f"run{i}"
        run(cfg, seed, d, quiet=True)
        runs.append({f["path"]: f for f in json.loads((d / "manifest.json").read_text())["files"]})
    a, b = runs
    diff = sorted(p for p in set(a) | set(b) if a.get(p, {}).get("sha256") != b.get(p, {}).get("sha256"))
    result = {"scale": cfg.name, "seed": seed, "files_compared": len(a), "identical": not diff,
              "differing_files": diff,
              "row_counts": {p: f["rows"] for p, f in sorted(a.items()) if f["rows"] is not None and p.startswith("data/csv")},
              "checksums": {p: f["sha256"] for p, f in sorted(a.items())}}
    if reference and (reference / "manifest.json").exists():
        ref = {f["path"]: f for f in json.loads((reference / "manifest.json").read_text())["files"]}
        rdiff = sorted(p for p in set(a) | set(ref) if a.get(p, {}).get("sha256") != ref.get(p, {}).get("sha256"))
        result["reference_output"] = str(reference)
        result["matches_reference"] = not rdiff
        result["reference_differing_files"] = rdiff
    return result
