"""Read access to pipeline outputs (output/<name>/...).

The web layer never re-implements the audit. It reads what `python -m freight_audit run`
wrote: the SQLite database (operational tables + audit outputs), the JSON reports, and the
ground-truth CSVs (shown side by side with the audit verdict, clearly labelled).
"""
from __future__ import annotations

import csv
import json
import re
import sqlite3
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "output"
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,80}$")


class NotFound(Exception):
    pass


class BadRequest(Exception):
    pass


class Busy(Exception):
    pass


# Datasets currently being (re)written by a job; reads return 409 until the job ends.
_busy: set[str] = set()
_busy_lock = threading.Lock()


def mark_busy(name: str, busy: bool) -> None:
    with _busy_lock:
        (_busy.add if busy else _busy.discard)(name)


def is_busy(name: str) -> bool:
    with _busy_lock:
        return name in _busy


def list_datasets() -> list[dict]:
    out = []
    if not OUTPUT.is_dir():
        return out
    for d in sorted(OUTPUT.iterdir()):
        if not d.is_dir() or not NAME_RE.match(d.name):
            continue
        mf = d / "manifest.json"
        busy = is_busy(d.name)
        if not mf.exists() and not busy:
            continue
        item = {"name": d.name, "busy": busy, "has_db": (d / "data" / "sql" / "freight_audit.sqlite").exists()}
        if mf.exists() and not busy:
            try:
                m = json.loads(mf.read_text(encoding="utf-8"))
                item.update(seed=m.get("seed"), scale=m.get("scale"), validation=m.get("validation"),
                            generated_at_utc=m.get("generated_at_utc"), runtime_seconds=m.get("runtime_seconds"),
                            row_counts=m.get("row_counts"), command=m.get("command"))
            except (OSError, ValueError):
                item["error"] = "manifest unreadable"
        out.append(item)
    return out


class Dataset:
    """One output directory. Instances are cheap; caches are keyed by file mtime."""

    _cache: dict = {}
    _cache_lock = threading.Lock()

    def __init__(self, name: str):
        if not NAME_RE.match(name or ""):
            raise NotFound(f"dataset {name!r}")
        self.name = name
        self.dir = OUTPUT / name
        if not (self.dir / "manifest.json").exists():
            raise NotFound(f"dataset {name!r}")
        if is_busy(name):
            raise Busy(f"dataset {name!r} is being regenerated by a running job")
        self.db_path = self.dir / "data" / "sql" / "freight_audit.sqlite"

    # ------------------------------------------------------------------ files
    def _cached(self, rel: str, loader):
        p = self.dir / rel
        if not p.exists():
            return None
        key = (str(p), p.stat().st_mtime_ns)
        with self._cache_lock:
            if key in self._cache:
                return self._cache[key]
        val = loader(p)
        with self._cache_lock:
            # drop stale entries for the same path
            for k in [k for k in self._cache if k[0] == key[0]]:
                del self._cache[k]
            self._cache[key] = val
        return val

    def json_file(self, rel: str):
        return self._cached(rel, lambda p: json.loads(p.read_text(encoding="utf-8")))

    def csv_file(self, rel: str) -> list[dict] | None:
        def load(p):
            with open(p, encoding="utf-8", newline="") as fh:
                return list(csv.DictReader(fh))
        return self._cached(rel, load)

    def manifest(self) -> dict:
        return self.json_file("manifest.json")

    def ground_truth_by_invoice(self) -> dict:
        def load(p):
            with open(p, encoding="utf-8", newline="") as fh:
                return {r["invoice_id"]: r for r in csv.DictReader(fh)}
        return self._cached("ground_truth/expected_invoice_outcomes.csv", load) or {}

    def ground_truth_labels(self) -> list[dict]:
        return self.csv_file("ground_truth/ground_truth.csv") or []

    def file_path(self, rel: str) -> Path:
        """Only files listed in the manifest (plus the manifest itself) can be downloaded."""
        listed = {f["path"] for f in self.manifest().get("files", [])} | {"manifest.json"}
        if rel not in listed:
            raise NotFound(rel)
        p = (self.dir / rel).resolve()
        if self.dir.resolve() not in p.parents or not p.is_file():
            raise NotFound(rel)
        return p

    # --------------------------------------------------------------- database
    def connect(self) -> sqlite3.Connection:
        if not self.db_path.exists():
            raise NotFound(f"dataset {self.name!r} has no SQLite database (only reports were kept). "
                           f"Regenerate it from the Run page.")
        uri = self.db_path.resolve().as_uri() + "?mode=ro"
        con = sqlite3.connect(uri, uri=True, check_same_thread=False)
        con.row_factory = sqlite3.Row
        return con

    def query(self, sql: str, params=()) -> list[dict]:
        con = self.connect()
        try:
            return [dict(r) for r in con.execute(sql, params)]
        finally:
            con.close()

    def one(self, sql: str, params=()) -> dict | None:
        rows = self.query(sql, params)
        return rows[0] if rows else None
